import { writeFileSync } from "node:fs";
import { resolve } from "node:path";
import { start, init } from "./rpc.mjs";
import { agents } from "./agents.mjs";
const [name, model2] = process.argv.slice(2); const a = agents[name];
const log = resolve(`out/${name}-stage4.log`); writeFileSync(log, "");
const updates = [];
const c = start(a.cmd, a.args, { log, onUpdate: (u) => updates.push(u) });
await init(c, { auth: { terminal: true } });
const show = async (m, p) => { try { console.log(m, JSON.stringify(await c.req(m, p, 20000)).slice(0, 1500)); } catch (e) { console.log(m, "ERR", e.message); } };
await show("auth/status", {});
const ns = await c.req("session/new", { cwd: resolve("out/repo"), mcpServers: [] });
const sid = ns.sessionId;
await show("session/status", { sessionId: sid });
await show("session/options", { sessionId: sid });
const eff = (opts) => opts.find((o) => o.category === "thought_level");
console.log("effort before:", JSON.stringify(eff(ns.configOptions)?.options.map((o) => o.value)));
const r = await c.req("session/set_config_option", { sessionId: sid, configId: "model", value: model2 });
console.log("effort after model", model2, ":", JSON.stringify(eff(r.configOptions)?.options.map((o) => o.value) ?? null), "ids:", r.configOptions.map((o) => o.id));
await show("session/close", { sessionId: sid });
c.kill(); process.exit(0);
