export const fileIconName = (path: string): string | undefined => {
	const name = (path.split("/").at(-1) ?? "").toLowerCase();
	const known = NAMES[name];
	if (known !== undefined) return known;
	for (const [prefix, icon] of PREFIXES) {
		if (name.startsWith(prefix)) return icon;
	}
	// The longest extension first: from the first dot after the name's start.
	for (
		let dot = name.indexOf(".", 1);
		dot >= 0;
		dot = name.indexOf(".", dot + 1)
	) {
		const icon = EXTENSIONS[name.slice(dot + 1)];
		if (icon !== undefined) return icon;
	}
	return undefined;
};
